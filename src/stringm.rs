impl<const MAX: u32> From<&StringM<MAX>> for Vec<u8> {
    fn from(v: &StringM<MAX>) -> Self {
        v.0.clone()
    }
}

impl<const MAX: u32> AsRef<Vec<u8>> for StringM<MAX> {
    fn as_ref(&self) -> &Vec<u8> {
        &self.0
    }
}

